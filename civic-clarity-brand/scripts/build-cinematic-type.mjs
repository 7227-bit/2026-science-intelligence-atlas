#!/usr/bin/env node
/**
 * Cinematic title geometry for the v2 ident (Revision Round 2).
 *
 * Fits Cinzel Bold / Montserrat Medium OUTLINES to the measured positions of
 * the lettering in the owner-selected reference (band coordinates, 1536 px
 * wide reference crop). The baked raster lettering of the reference is
 * removed from the plate and replaced by these vector outlines, so the
 * title is crisp at 4K, spelled from font data and animatable.
 *
 * Does NOT modify the approved-candidate logo masters (scripts/build-logos.mjs).
 * Output: src/brand/generated/cinematicType.json
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import opentype from 'opentype.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fDisplay = opentype.loadSync(path.join(ROOT, 'public/fonts/Cinzel_700Bold.ttf'));
const fSupport = opentype.loadSync(path.join(ROOT, 'public/fonts/Montserrat_500Medium.ttf'));
const r2 = (n) => Math.round(n * 100) / 100;

/* Measured from references/OWNER_SELECTED_REFERENCE.jpeg (crop 1536x446 @ 0,0) — see QA_REPORT_V2.md */
const REF = {
  baseline: 341,
  smallCapH: 89,
  initialH: 132,
  civic: [201, 654],
  clarity: [666, 1332],
  descriptor: {x1: 386, x2: 1174, capTop: 379, baseline: 397, wordGap: 39},
  glowLineY: 357,
  flankRuleY: 389.5,
  flankLeft: [248, 353],
  flankRight: [1204, 1304],
  lowerRuleY: 417,
  lowerLeft: [422, 735],
  lowerRight: [802, 1162],
  star: {cx: 768, cy: 423, r: 19},
};

const capOf = (f, ch) => f.charToGlyph(ch).getBoundingBox().y2 / f.unitsPerEm;

function layoutWord(f, text, sizeFor, tracking) {
  const out = [];
  let x = 0;
  let prev = null;
  for (let i = 0; i < text.length; i++) {
    const size = sizeFor(i);
    const g = f.charToGlyph(text[i]);
    if (prev) x += (f.getKerningValue(prev.g, g) * Math.min(size, prev.size)) / f.unitsPerEm;
    const p = g.getPath(x, 0, size);
    out.push({char: text[i], x, size, path: p, bbox: p.getBoundingBox()});
    x += (g.advanceWidth * size) / f.unitsPerEm + tracking;
    prev = {g, size};
  }
  const x1 = Math.min(...out.map((o) => o.bbox.x1));
  const x2 = Math.max(...out.map((o) => o.bbox.x2));
  return {glyphs: out, x1, x2, width: x2 - x1};
}

/** Solve tracking so the word's visible width equals `target` (bisection). */
function fitWord(f, text, sizeFor, target) {
  let lo = -40, hi = 60;
  for (let k = 0; k < 50; k++) {
    const mid = (lo + hi) / 2;
    if (layoutWord(f, text, sizeFor, mid).width > target) hi = mid;
    else lo = mid;
  }
  return {tracking: (lo + hi) / 2, layout: layoutWord(f, text, sizeFor, (lo + hi) / 2)};
}

const smallSize = REF.smallCapH / capOf(fDisplay, 'I');
const initialScale = REF.initialH / REF.smallCapH;
const sizeFor = (i) => (i === 0 ? smallSize * initialScale : smallSize);

const words = [];
for (const [text, [x1, x2]] of [
  ['CIVIC', REF.civic],
  ['CLARITY', REF.clarity],
]) {
  const {tracking, layout} = fitWord(fDisplay, text, sizeFor, x2 - x1);
  const dx = x1 - layout.x1;
  words.push({
    text,
    tracking: r2(tracking),
    glyphs: layout.glyphs.map((g) => {
      const p = fDisplay.charToGlyph(g.char).getPath(g.x + dx, REF.baseline, g.size);
      const bb = p.getBoundingBox();
      return {char: g.char, d: p.toPathData(2), cx: r2((bb.x1 + bb.x2) / 2), bbox: [r2(bb.x1), r2(bb.y1), r2(bb.x2), r2(bb.y2)]};
    }),
  });
}

// Descriptor: two words, sized by cap height, tracking solved to measured span with the measured word gap.
const D = REF.descriptor;
const dSize = (D.baseline - D.capTop) / capOf(fSupport, 'I');
const dWords = ['INVESTIGATIVE', 'DOCUMENTARIES'];
let lo = 0, hi = 30, best;
for (let k = 0; k < 50; k++) {
  const t = (lo + hi) / 2;
  const a = layoutWord(fSupport, dWords[0], () => dSize, t);
  const b = layoutWord(fSupport, dWords[1], () => dSize, t);
  const w = a.width + D.wordGap + b.width;
  best = {t, a, b};
  if (w > D.x2 - D.x1) hi = t;
  else lo = t;
}
const descGlyphs = [];
{
  const {t, a, b} = best;
  const ax = D.x1 - a.x1;
  const bx = D.x1 + a.width + D.wordGap - b.x1;
  for (const [lay, off] of [
    [a, ax],
    [b, bx],
  ])
    for (const g of lay.glyphs) {
      const p = fSupport.charToGlyph(g.char).getPath(g.x + off, D.baseline, dSize);
      descGlyphs.push({char: g.char, d: p.toPathData(2)});
    }
  var descTracking = t;
}

const out = {
  $comment: 'GENERATED by scripts/build-cinematic-type.mjs — v2 ident title geometry in reference-band units (1536-wide crop). Do not edit by hand.',
  units: 'reference band px (OWNER_SELECTED_REFERENCE.jpeg crop 1536x446 @0,0)',
  font: {display: 'Cinzel Bold (OFL)', support: 'Montserrat Medium (OFL)'},
  smallCapSize: r2(smallSize),
  initialScale: r2(initialScale),
  words,
  wordGap: REF.clarity[0] - REF.civic[1],
  descriptor: {size: r2(dSize), tracking: r2(descTracking), glyphs: descGlyphs, text: 'INVESTIGATIVE DOCUMENTARIES'},
  ref: REF,
};
fs.writeFileSync(path.join(ROOT, 'src/brand/generated/cinematicType.json'), JSON.stringify(out, null, 1));
console.log(
  `cinematic type: small-cap size ${r2(smallSize)}, initials x${r2(initialScale)}, tracking CIVIC ${words[0].tracking} / CLARITY ${words[1].tracking}, word gap ${out.wordGap}; descriptor size ${r2(dSize)} tracking ${r2(descTracking)}`,
);
